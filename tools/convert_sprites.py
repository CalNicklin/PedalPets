#!/usr/bin/env python3
"""Slice Evil Wizard sprite sheets, auto-crop, scale, convert to RGB565,
emit one C header per animation state for the ESP32 firmware."""

import os
from PIL import Image

SRC = "/Users/Cal/Documents/projects/PedalPets/sprites/EVil Wizard 2/Sprites"
OUT = "/Users/Cal/Documents/projects/PedalPets/src/sprites"
TARGET_H = 96  # px on screen — leaves headroom on 128-tall display
TRANSPARENT = (0, 0, 0)  # bake background straight in — no transparency needed

# (sheet filename, frame size, our state name)
STATES = [
    ("Idle.png",    250, "idle"),
    ("Run.png",     250, "run"),
    ("Attack1.png", 250, "attack"),
]

def to_rgb565(r, g, b):
    # Swap R/B for BGR-wired ST7735 panels.
    return ((b & 0xF8) << 8) | ((g & 0xFC) << 3) | (r >> 3)

def slice_sheet(path, frame_w):
    sheet = Image.open(path).convert("RGBA")
    n = sheet.width // frame_w
    return [sheet.crop((i * frame_w, 0, (i + 1) * frame_w, sheet.height)) for i in range(n)]

def union_bbox(frames):
    box = None
    for f in frames:
        b = f.getbbox()
        if not b: continue
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]),
                                      max(box[2], b[2]), max(box[3], b[3]))
    return box

def process(sheet_name, frame_w, state):
    frames = slice_sheet(os.path.join(SRC, sheet_name), frame_w)
    box = union_bbox(frames)
    cropped = [f.crop(box) for f in frames]

    src_h = box[3] - box[1]
    src_w = box[2] - box[0]
    scale = TARGET_H / src_h
    out_h = TARGET_H
    out_w = max(1, int(round(src_w * scale)))
    scaled = [f.resize((out_w, out_h), Image.NEAREST) for f in cropped]

    # Flatten alpha onto magenta key
    flat = []
    for f in scaled:
        bg = Image.new("RGB", f.size, TRANSPARENT)
        bg.paste(f, mask=f.split()[3])
        flat.append(bg)

    # Convert to RGB565
    pixels_per_frame = out_w * out_h
    data = []
    for f in flat:
        for r, g, b in f.getdata():
            data.append(to_rgb565(r, g, b))

    return out_w, out_h, len(flat), data

def emit_header(state, w, h, n, data):
    path = os.path.join(OUT, f"sprite_{state}.h")
    with open(path, "w") as f:
        f.write(f"// Auto-generated by tools/convert_sprites.py — do not edit.\n")
        f.write(f"#pragma once\n#include <Arduino.h>\n\n")
        f.write(f"constexpr uint16_t {state.upper()}_W = {w};\n")
        f.write(f"constexpr uint16_t {state.upper()}_H = {h};\n")
        f.write(f"constexpr uint16_t {state.upper()}_FRAMES = {n};\n")
        f.write(f"constexpr uint16_t {state.upper()}_TRANSPARENT = 0xF81F;\n\n")
        f.write(f"const uint16_t {state.upper()}_DATA[{w*h*n}] PROGMEM = {{\n")
        for i in range(0, len(data), 16):
            f.write("  " + ", ".join(f"0x{p:04X}" for p in data[i:i+16]) + ",\n")
        f.write("};\n")
    print(f"  → {path} ({w}x{h}, {n} frames, {len(data)*2} bytes)")

def main():
    os.makedirs(OUT, exist_ok=True)
    for sheet, fw, state in STATES:
        print(f"{state}: slicing {sheet}")
        w, h, n, data = process(sheet, fw, state)
        emit_header(state, w, h, n, data)

if __name__ == "__main__":
    main()
