"""Turn a paper-doll part library into firmware tables.

Usage:  uv run tools/build_doll.py <doll_dir>

<doll_dir>/parts.json comes from art/blender/<char>_doll.py; <doll_dir>/poses/
holds the inked part images (full canvas, transparent background). Emits:
  src/gen/doll_meta.h    plain C++ tables (core + tests can include it)
  src/gen/doll_pixels.h  4-bit palette pixels, palette, background (renderer only)
  src/gen/pack.h         marks the build as a paper-doll pack
"""

import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
import build_art as ba  # noqa: E402

OUT = ba.OUT
HEADER = "// Auto-generated by tools/build_doll.py — do not edit."
BACKGROUND = {"color": "#ece6da", "sun": "#dfa58f"}


class DollError(Exception):
    pass


def fail(msg):
    raise DollError(msg)


def q4(v):
    return int(round(v * 4))


def build(doll_dir):
    doll_dir = Path(doll_dir)
    meta = json.loads((doll_dir / "parts.json").read_text())
    channels = meta["channels"]
    pal = [ba.hex_rgb(c["out"]) for c in meta["palette"]]
    names = [p["name"] for p in meta["parts"]]
    index = {n: i for i, n in enumerate(names)}

    children = {n: [c["name"] for c in meta["parts"] if c.get("parent") == n] for n in names}
    parts, images, anchors, axis_values, pixels = [], [], [], [], []
    for i, p in enumerate(meta["parts"]):
        parent = p.get("parent")
        if parent is not None and index.get(parent, len(names)) >= i:
            fail(f"part {p['name']}: parent {parent!r} must be listed before it")
        axes = []
        for ax in p["axes"]:
            mask = 0
            for src in ax["sources"]:
                if src not in channels:
                    fail(f"part {p['name']} axis {ax['name']}: unknown channel {src!r}")
                mask |= 1 << channels.index(src)
            axes.append((len(ax["values"]), len(axis_values), mask))
            axis_values += [q4(v) for v in ax["values"]]   # quarter units
        kids = children[p["name"]]
        first_image = len(images)
        for img in p["images"]:
            im = Image.open(doll_dir / "poses" / img["file"]).convert("RGBA")
            box = im.getchannel("A").getbbox() or (0, 0, 1, 1)
            crop = im.crop(box)
            first_anchor = len(anchors)
            for k in kids:
                ax, ay = img["anchors"][k]
                anchors.append((q4(ax), q4(ay)))
            images.append((box[0], box[1], box[2] - box[0], box[3] - box[1],
                           q4(img["pivot"][0]), q4(img["pivot"][1]), first_anchor))
            pixels.append(ba.pack_pal4(crop, pal, f"{p['name']}/{img['file']}"))
        parts.append({"name": p["name"], "parent": index[parent] if parent else -1,
                      "slot": children[parent].index(p["name"]) if parent else 0,
                      "axes": axes, "first_image": first_image, "count": len(p["images"])})

    return {"parts": parts, "images": images, "anchors": anchors, "axis_values": axis_values,
            "pixels": pixels, "palette": pal, "channels": channels,
            "draw_order": [index[n] for n in meta["draw_order"]],
            "hop": channels.index("hop") if "hop" in channels else -1,
            "canvas": meta["canvas"]}


def emit_meta(t):
    out = [HEADER, "#pragma once", '#include "../core/doll.h"', "", "namespace doll_gen {", ""]
    out += [f"constexpr int CANVAS_W = {t['canvas'][0]};", f"constexpr int CANVAS_H = {t['canvas'][1]};", ""]
    out.append("enum Channel : uint8_t { " + ", ".join(f"CH_{c.upper()} = {i}" for i, c in enumerate(t["channels"]))
               + f", CHANNEL_COUNT = {len(t['channels'])} }};")
    out.append("static const char* const CHANNEL_NAMES[] = {" + ", ".join(f'"{c}"' for c in t["channels"]) + "};")
    out.append("enum Part : uint8_t { " + ", ".join(f"P_{p['name'].upper()} = {i}" for i, p in enumerate(t["parts"]))
               + f", PART_COUNT = {len(t['parts'])} }};")
    out.append("")
    out.append("static const int16_t AXIS_VALUES[] = {" + ", ".join(map(str, t["axis_values"])) + "};")
    out.append("static const DollAnchor ANCHORS[] = {" + ", ".join(f"{{{x}, {y}}}" for x, y in t["anchors"]) + "};")
    out.append("static const DollImage IMAGES[] = {")
    for im in t["images"]:
        out.append("  {" + ", ".join(map(str, im)) + "},")
    out.append("};")
    out.append("static const DollPart PARTS[] = {")
    for p in t["parts"]:
        axes = [f"{{{c}, {f}, {m}}}" for c, f, m in p["axes"]] + ["{0, 0, 0}"] * (3 - len(p["axes"]))
        out.append(f"  {{{p['parent']}, {p['slot']}, {len(p['axes'])}, {{{', '.join(axes)}}}, "
                   f"{p['first_image']}, {p['count']}}},  // {p['name']}")
    out.append("};")
    out.append("static const uint8_t DRAW_ORDER[] = {" + ", ".join(map(str, t["draw_order"])) + "};")
    out += ["", "static const DollTables DOLL = {",
            f"  PARTS, {len(t['parts'])}, DRAW_ORDER, IMAGES, ANCHORS, AXIS_VALUES,",
            f"  {len(t['channels'])}, {t['hop']},", "};", "", "}  // namespace doll_gen", ""]
    return "\n".join(out)


def emit_pixels(t):
    rgb = ba.rgb565_hex
    out = [HEADER, "#pragma once", "#include <Arduino.h>", "", "namespace doll_gen {", ""]
    out += [f"constexpr uint16_t BG_COLOR = {rgb(ba.hex_rgb(BACKGROUND['color']))};",
            f"constexpr uint16_t SUN_COLOR = {rgb(ba.hex_rgb(BACKGROUND['sun']))};",
            "static const uint16_t PALETTE[16] = {0x0000, " + ", ".join(rgb(c) for c in t["palette"]) + "};", ""]
    for i, data in enumerate(t["pixels"]):
        out.append(f"static const uint8_t PIX_{i}[{len(data)}] PROGMEM = {{"
                   + ", ".join(f"0x{v:02X}" for v in data) + "};")
    out.append("static const uint8_t* const PIXELS[] = {" + ", ".join(f"PIX_{i}" for i in range(len(t["pixels"]))) + "};")
    out += ["", "}  // namespace doll_gen", ""]
    return "\n".join(out)


def main():
    try:
        t = build(sys.argv[1])
    except (DollError, ba.ArtError) as e:
        print(f"build_doll: {e}", file=sys.stderr)
        sys.exit(1)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "doll_meta.h").write_text(emit_meta(t))
    (OUT / "doll_pixels.h").write_text(emit_pixels(t))
    (OUT / "pack.h").write_text(f"{HEADER}\n#pragma once\n#define PEDALPETS_DOLL 1\n")
    size = sum(len(p) for p in t["pixels"])
    print(f"build_doll: {len(t['parts'])} parts, {len(t['images'])} images ({size / 1024:.0f} KB pixels)")


if __name__ == "__main__":
    main()
