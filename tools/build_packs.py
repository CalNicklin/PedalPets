#!/usr/bin/env python3
"""Write src/gen/packs.h: every character and scene pack that has been built.

Usage:  python3 tools/build_packs.py     (build_moves.py and build_scene.py run it)

Characters come from src/gen/chars/<name>/character.h, scenes from
src/gen/scenes/<name>/scene.h. The first character and scene are the defaults.
"""

from pathlib import Path

GEN = Path(__file__).resolve().parent.parent / "src" / "gen"
ORDER = ["jay"]   # preferred first (the default); the rest follow alphabetically


def names(kind, header):
    found = sorted(d.name for d in (GEN / kind).glob("*") if (d / header).exists())
    return sorted(found, key=lambda n: (ORDER.index(n) if n in ORDER else len(ORDER), n))


def emit(chars, scenes):
    out = ["// Auto-generated by tools/build_packs.py — do not edit.", "#pragma once", '#include "../core/pack.h"']
    out += [f'#include "chars/{c}/character.h"' for c in chars]
    out += [f'#include "scenes/{s}/scene.h"' for s in scenes]
    out += ["", "static const Character* const CHARACTERS[] = {" + ", ".join(f"&{c}_gen::CHARACTER" for c in chars) + "};",
            f"constexpr int CHARACTER_COUNT = {len(chars)};",
            "static const Scene* const SCENES[] = {" + ", ".join(f"&{s}_scene::SCENE" for s in scenes) + "};",
            f"constexpr int SCENE_COUNT = {len(scenes)};", ""]
    return "\n".join(out)


def main():
    chars, scenes = names("chars", "character.h"), names("scenes", "scene.h")
    (GEN / "packs.h").write_text(emit(chars, scenes))
    print(f"build_packs: characters {chars}, scenes {scenes}")


if __name__ == "__main__":
    main()
