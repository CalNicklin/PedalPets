"""Compile a backdrop scene (art/scenes/<name>.py) into firmware data.

Usage:  uv run tools/build_scene.py <name>        e.g. forest

Writes src/gen/scene.h (backdrop as byte-swapped RGB565, ready to copy into
the frame buffer; leaf sprites as 4-bit palette) and art/scenes/<name>/ PNGs
for tools/doll_timeline.py.
"""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "gen"
sys.path.insert(0, str(Path(__file__).parent))
import build_art as ba  # noqa: E402


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "art" / "scenes" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def swapped565(r, g, b):
    v = ba.to_rgb565(r, g, b)                 # R/B swapped for the BGR panel
    return ((v >> 8) | (v << 8)) & 0xFFFF     # byte order of the sprite buffer


def main():
    name = sys.argv[1]
    mod = load(name)
    bg = mod.draw().convert("RGB")
    sprites = mod.leaf_sprites()
    colours = len(sprites)
    rotations = len(sprites[0])
    pal = [tuple(c) for c in mod.LEAF_COLOURS]

    flat, sizes, pix = [], [], []
    for c in range(colours):
        for r in range(rotations):
            for e in range(2):
                im = sprites[c][r][e]
                flat.append(im)
                sizes.append(im.size)
                pix.append(ba.pack_pal4(im, pal, f"leaf {c}/{r}/{e}"))

    raw = bg.tobytes()
    words = [swapped565(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
    out = ["// Auto-generated by tools/build_scene.py — do not edit.", "#pragma once", "#include <Arduino.h>", "",
           "#define PEDALPETS_SCENE 1", "", "namespace scene_gen {", "",
           f"constexpr int LEAF_COLOURS = {colours};", f"constexpr int LEAF_ROTATIONS = {rotations};",
           f"constexpr float FEET_Y = {mod.FEET_Y};", ""]
    out.append(f"static const uint16_t BACKDROP[{len(words)}] PROGMEM = {{")
    for i in range(0, len(words), 16):
        out.append("  " + ", ".join(f"0x{w:04X}" for w in words[i:i + 16]) + ",")
    out.append("};")
    out.append("static const uint16_t LEAF_PALETTE[16] = {0x0000, " + ", ".join(ba.rgb565_hex(c) for c in pal) + "};")
    for i, d in enumerate(pix):
        out.append(f"static const uint8_t LEAF_{i}[] = {{" + ", ".join(f"0x{v:02X}" for v in d) + "};")
    out.append("static const uint8_t* const LEAF_PIXELS[] = {" + ", ".join(f"LEAF_{i}" for i in range(len(pix))) + "};")
    out.append("static const uint8_t LEAF_SIZES[][2] = {" + ", ".join(f"{{{w}, {h}}}" for w, h in sizes) + "};")
    out += ["", "// Sprite for a leaf: (colour * LEAF_ROTATIONS + rotation) * 2 + edge-on",
            "inline int leafSprite(int colour, int rotation, bool edge) {",
            "  return (colour * LEAF_ROTATIONS + rotation) * 2 + (edge ? 1 : 0);", "}", "",
            "}  // namespace scene_gen", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "scene.h").write_text("\n".join(out))
    (OUT / "scene_consts.h").write_text(
        "// Auto-generated by tools/build_scene.py — do not edit. (Arduino-free, for the simulator.)\n"
        f"constexpr int LEAF_COLOURS = {colours};\nconstexpr int LEAF_ROTATIONS = {rotations};\n"
        f"constexpr float FEET_Y = {mod.FEET_Y};\n")

    d = ROOT / "art" / "scenes" / name
    (d / "leaves").mkdir(parents=True, exist_ok=True)
    bg.save(d / "backdrop.png")
    for i, im in enumerate(flat):
        im.save(d / "leaves" / f"{i}.png")
    (d / "scene.json").write_text(json.dumps({"leaves": len(flat), "feet_y": mod.FEET_Y}))
    print(f"build_scene: {name}: backdrop {len(words) * 2 // 1024} KB, {len(flat)} leaf sprites")


if __name__ == "__main__":
    main()
