"""Compile a backdrop scene (art/scenes/<name>.py) into firmware data.

Usage:  uv run tools/build_scene.py <name>        e.g. forest

Writes src/gen/scenes/<name>/scene.h (a Scene pack: backdrop as byte-swapped
RGB565, ready to copy into the frame buffer; leaf sprites as 4-bit palette),
refreshes src/gen/packs.h, and writes art/scenes/<name>/ PNGs for
tools/doll_timeline.py.
"""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "gen"
sys.path.insert(0, str(Path(__file__).parent))
import build_art as ba  # noqa: E402


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "art" / "scenes" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def swapped565(r, g, b):
    v = ba.to_rgb565(r, g, b)                 # R/B swapped for the BGR panel
    return ((v >> 8) | (v << 8)) & 0xFFFF     # byte order of the sprite buffer


def main():
    name = sys.argv[1]
    mod = load(name)
    bg = mod.draw().convert("RGB")
    sprites = mod.leaf_sprites()
    colours = len(sprites)
    rotations = len(sprites[0])
    pal = [tuple(c) for c in mod.LEAF_COLOURS]

    flat, sizes, pix = [], [], []
    for c in range(colours):
        for r in range(rotations):
            for e in range(2):
                im = sprites[c][r][e]
                flat.append(im)
                sizes.append(im.size)
                pix.append(ba.pack_pal4(im, pal, f"leaf {c}/{r}/{e}"))

    raw = bg.tobytes()
    words = [swapped565(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
    ns = f"{name}_scene"
    out = ["// Auto-generated by tools/build_scene.py — do not edit.", "#pragma once", '#include "../../../core/pack.h"',
           "", f"namespace {ns} {{", ""]
    out.append(f"static const uint16_t BACKDROP[{len(words)}] = {{")
    for i in range(0, len(words), 16):
        out.append("  " + ", ".join(f"0x{w:04X}" for w in words[i:i + 16]) + ",")
    out.append("};")
    out.append("static const uint16_t LEAF_PALETTE[16] = {0x0000, " + ", ".join(ba.rgb565_hex(c) for c in pal) + "};")
    for i, d in enumerate(pix):
        out.append(f"static const uint8_t LEAF_{i}[] = {{" + ", ".join(f"0x{v:02X}" for v in d) + "};")
    out.append("static const uint8_t* const LEAF_PIXELS[] = {" + ", ".join(f"LEAF_{i}" for i in range(len(pix))) + "};")
    out.append("static const uint8_t LEAF_SIZES[][2] = {" + ", ".join(f"{{{w}, {h}}}" for w, h in sizes) + "};")
    out += ["", f'static const Scene SCENE = {{"{name}", BACKDROP, {float(mod.FEET_Y)}f, {colours}, {rotations}, '
            "LEAF_PALETTE, LEAF_PIXELS, LEAF_SIZES};", "", f"}}  // namespace {ns}", ""]
    dest = OUT / "scenes" / name
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "scene.h").write_text("\n".join(out))
    import build_packs
    build_packs.main()

    d = ROOT / "art" / "scenes" / name
    (d / "leaves").mkdir(parents=True, exist_ok=True)
    bg.save(d / "backdrop.png")
    for i, im in enumerate(flat):
        im.save(d / "leaves" / f"{i}.png")
    (d / "scene.json").write_text(json.dumps({"leaves": len(flat), "feet_y": mod.FEET_Y}))
    print(f"build_scene: {name}: backdrop {len(words) * 2 // 1024} KB, {len(flat)} leaf sprites")


if __name__ == "__main__":
    main()
