#!/usr/bin/env python3
"""Write a character's manifest.toml from its Blender actions (actions.json).

Usage:  python3 tools/pet_manifest.py <actions.json> <poses_dir> <manifest_out>

Every rendered frame becomes a pose held for one display frame (30 ms), so
idles and reactions play "on ones". Loops hand over on their first frame.
"""

import json
import sys
from pathlib import Path

FRAME_MS = 30


def main():
    data = json.loads(Path(sys.argv[1]).read_text())
    actions = data["actions"]
    palette = [c["out"] for c in data["palette"]]
    poses_dir = Path(sys.argv[2])
    out = Path(sys.argv[3])
    rel = poses_dir.relative_to(Path.cwd()) if poses_dir.is_absolute() else poses_dir

    lines = [
        "# Generated by tools/pet_manifest.py from art/blender renders — do not edit.",
        "",
        "[palette]",
        "colors = [" + ", ".join(f'"{c}"' for c in palette) + "]",
        "",
        "[background]",
        'color = "#ece6da"',
        'sun   = "#dfa58f"',
        "",
    ]
    for name, a in actions.items():
        for f in range(a["count"]):
            lines += [f"[poses.{name}_{f:02d}]", f'src  = "{rel}/{name}_{f:02d}.png"', 'eyes = "baked"', ""]

    for name, a in actions.items():
        if "idle" not in a:
            continue
        frames = ", ".join(f'"{name}_{f:02d}"' for f in range(a["count"]))
        lines += [f"[idles.{a['idle']}]", f"poses  = [{frames}]", f"period = {FRAME_MS}", ""]

    for name, a in actions.items():
        if "trigger" not in a:
            continue
        lines += ["[[reactions]]", f'id      = "{name}"', f'trigger = "{a["trigger"]}"']
        if "loop_len" in a:
            lines += [f"loop_from = {a['loop_from']}", f"loop_len  = {a['loop_len']}"]
        if "entry_window" in a:
            lines += [f"entry_window = {a['entry_window']}"]
        if "loop_until" in a:
            lines += [f'loop_until = "{a["loop_until"]}"', f"loop_max   = {a['loop_max']}"]
        steps = []
        if "freeze_ms" in a:   # hold whatever is on screen first (Cut)
            steps.append(f'  {{ pose = "@current", hold = {a["freeze_ms"]} }},')
        steps += [f'  {{ pose = "{name}_{f:02d}", hold = {FRAME_MS} }},' for f in range(a["count"])]
        if "freeze_ms" in a and "loop_len" in a:
            sys.exit(f"{name}: freeze_ms shifts step indices; adjust loop_from")
        lines += ["steps = [", *steps, "]", ""]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"manifest -> {out} ({sum(a['count'] for a in actions.values())} poses)")


if __name__ == "__main__":
    main()
